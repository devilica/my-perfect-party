function deepClone(o) {
  return JSON.parse(JSON.stringify(o));
}

function countKeys(o) {
  return Object.entries(o).reduce(
    (n, [, v]) => (typeof v === 'object' && v !== null && !Array.isArray(v) ? n + countKeys(v) : n + 1),
    0,
  );
}

function deepMergeFromTemplate(template, translations) {
  const result = {};
  for (const key of Object.keys(template)) {
    const templateVal = template[key];
    const transVal = translations[key];
    if (typeof templateVal === 'object' && templateVal !== null && !Array.isArray(templateVal)) {
      if (typeof transVal !== 'object' || transVal === null || Array.isArray(transVal)) {
        throw new Error(`Missing nested translations at "${key}"`);
      }
      result[key] = deepMergeFromTemplate(templateVal, transVal);
    } else {
      if (transVal === undefined) {
        throw new Error(`Missing translation for key "${key}"`);
      }
      result[key] = transVal;
    }
  }
  return result;
}

function validateStructure(template, output, path = '') {
  for (const key of Object.keys(template)) {
    const p = path ? `${path}.${key}` : key;
    if (!(key in output)) {
      throw new Error(`Missing key in output: ${p}`);
    }
    if (typeof template[key] === 'object' && template[key] !== null && !Array.isArray(template[key])) {
      validateStructure(template[key], output[key], p);
    }
  }
  for (const key of Object.keys(output)) {
    if (!(key in template)) {
      throw new Error(`Extra key in output: ${path ? `${path}.${key}` : key}`);
    }
  }
}

function assertPlaceholders(enVal, outVal, path) {
  const re = /\{\{[^}]+\}\}/g;
  const enPh = (enVal.match(re) || []).sort().join(',');
  const outPh = (String(outVal).match(re) || []).sort().join(',');
  if (enPh !== outPh) {
    throw new Error(`Placeholder mismatch at ${path}: expected [${enPh}] got [${outPh}]`);
  }
}

function validatePlaceholders(template, output, path = '') {
  for (const key of Object.keys(template)) {
    const p = path ? `${path}.${key}` : key;
    if (typeof template[key] === 'object' && template[key] !== null && !Array.isArray(template[key])) {
      validatePlaceholders(template[key], output[key], p);
    } else {
      assertPlaceholders(template[key], output[key], p);
    }
  }
}

