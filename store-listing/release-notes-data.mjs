export function validateReleaseNotes(maxLen = 500) {
  const issues = [];
  for (const [locale, text] of Object.entries(releaseNotes)) {
    if ([...text].length > maxLen) {
      issues.push(`${locale}: ${[...text].length} chars (max ${maxLen})`);
    }
  }
  return issues;
}
